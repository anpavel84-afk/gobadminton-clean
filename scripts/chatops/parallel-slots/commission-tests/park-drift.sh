# Reject symlinks in every ancestor, including the final component if present.
no_symlinks() {
    isolated_python - "$@" <<'PY'
import os, stat, sys
from pathlib import Path
for name in sys.argv[1:]:
    path = Path(name)
    if not path.is_absolute():
        sys.exit(1)
    for part in reversed((path, *path.parents)):
        try:
            info = part.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode):
            sys.exit(1)
PY
}

root_private() {
    no_symlinks "$1" || fail 3 'Symlink in backup path'
    if [[ -e $1 ]]; then
        [[ -d $1 && $(stat -c '%u:%g:%a' -- "$1") == 0:0:700 ]] || fail 3 'Unsafe backup directory'
    else
        install -d -o root -g root -m 0700 -- "$1"
    fi
}

# All path components are opened without following symlinks. Root only reads
# user files through these descriptors; every user-path mutation runs as ACCOUNT.
file_helper() {
    cat <<'PY'
import hashlib, os, secrets, stat, sys

DIR_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC

def directory(path):
    if not path.startswith('/') or any(p in ('.', '..') for p in path.split('/')):
        raise ValueError('absolute path required')
    fd = os.open('/', DIR_FLAGS)
    try:
        for part in path.split('/'):
            if part:
                child = os.open(part, DIR_FLAGS, dir_fd=fd)
                os.close(fd)
                fd = child
        return fd
    except BaseException:
        os.close(fd)
        raise

def read_file(path, expected='-', owner='-', group='-', mode='-'):
    parent, name = os.path.split(path)
    dfd = directory(parent)
    try:
        fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=dfd)
        with os.fdopen(fd, 'rb') as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode):
                raise ValueError('regular file required')
            for actual, wanted, base in ((info.st_uid, owner, 10), (info.st_gid, group, 10),
                                         (stat.S_IMODE(info.st_mode), mode, 8)):
                if wanted != '-' and actual != int(wanted, base):
                    raise ValueError('file metadata mismatch')
            data = stream.read()
            digest = hashlib.sha256(data).hexdigest()
            if expected != '-' and digest != expected:
                raise ValueError('file checksum mismatch')
            def identity(s):
                return (s.st_dev, s.st_ino, s.st_mode, s.st_uid, s.st_gid,
                        s.st_size, s.st_mtime_ns, s.st_ctime_ns)
            if (identity(info) != identity(os.fstat(stream.fileno())) or
                    identity(info) != identity(os.stat(name, dir_fd=dfd, follow_symlinks=False))):
                raise ValueError('file changed during read')
            return data, info, digest
    finally:
        os.close(dfd)

def main():
    operation, path, *args = sys.argv[1:]
    if operation in ('sha', 'info', 'read', 'verify'):
        data, info, digest = read_file(path, *args)
        if operation == 'sha':
            print(digest)
        elif operation == 'info':
            print(info.st_uid, info.st_gid, format(stat.S_IMODE(info.st_mode), 'o'))
        elif operation == 'read':
            sys.stdout.buffer.write(data)
        return
    if operation == 'snapshot':
        destination, *checks = args
        data, _, _ = read_file(path, *checks)
        dfd = directory(os.path.dirname(destination))
        try:
            fd = os.open(os.path.basename(destination), os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                         os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=dfd)
            with os.fdopen(fd, 'wb') as stream:
                stream.write(data)
                stream.flush()
                os.fsync(stream.fileno())
        finally:
            os.close(dfd)
        return
    if operation == 'directory':
        owner, group, mode = args
        if os.geteuid() != int(owner):
            raise ValueError('wrong writer uid')
        dfd = directory(os.path.dirname(path))
        try:
            name = os.path.basename(path)
            try:
                os.mkdir(name, 0o700, dir_fd=dfd)
            except FileExistsError:
                pass
            fd = os.open(name, DIR_FLAGS, dir_fd=dfd)
            try:
                if os.fstat(fd).st_uid != int(owner):
                    raise ValueError('directory owner mismatch')
                if mode != '-':
                    os.fchown(fd, int(owner), int(group))
                    os.fchmod(fd, int(mode, 8))
            finally:
                os.close(fd)
        finally:
            os.close(dfd)
        return
    if operation not in ('replace', 'remove'):
        raise ValueError('unknown operation')
    owner, group, mode, expected = args
    if os.geteuid() != int(owner):
        raise ValueError('wrong writer uid')
    data = sys.stdin.buffer.read() if operation == 'replace' else b''
    if operation == 'replace' and hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('replacement checksum mismatch')
    try:
        dfd = directory(os.path.dirname(path))
    except FileNotFoundError:
        if operation == 'remove':
            return
        raise
    temporary = None
    try:
        name = os.path.basename(path)
        if operation == 'remove':
            try:
                os.unlink(name, dir_fd=dfd)
            except FileNotFoundError:
                pass
            return
        temporary = '.' + name + '.park-drift.' + secrets.token_hex(16)
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW |
                     os.O_CLOEXEC, 0o600, dir_fd=dfd)
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fchown(stream.fileno(), int(owner), int(group))
            os.fchmod(stream.fileno(), int(mode, 8))
            os.fsync(stream.fileno())
            os.replace(temporary, name, src_dir_fd=dfd, dst_dir_fd=dfd)
            temporary = None
        os.fsync(dfd)
    finally:
        if temporary is not None:
            os.unlink(temporary, dir_fd=dfd)
        os.close(dfd)

try:
    main()
except (OSError, ValueError):
    print('Unsafe file operation', file=sys.stderr)
    sys.exit(1)
PY
}

file_ops() { isolated_python -c "$(file_helper)" "$@"; }
user_files() (
    local group
    group=$(isolated_python -c 'import grp, sys; print(grp.getgrgid(int(sys.argv[1])).gr_name)' "$1") || return 1
    shift
    cd / || return 1
    # The preserved group need not be a supplementary group of ACCOUNT.
    runuser -u "$ACCOUNT" -g "$group" -- env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin LANG=C.UTF-8 /usr/bin/python3 -I -c "$(file_helper)" "$@"
)
trusted_read() { file_ops read "$1" "${2:--}" "$EUID" "$(id -g)" 600; }
snapshot_file() { file_ops snapshot "$1" "$2" "$3" "$4" "$5" "$6"; }

atomic_file() {
    local source=$1 destination=$2 owner=$3 group=$4 permissions=$5 expected=$6
    no_symlinks "$destination" || return 1
    trusted_read "$source" "$expected" | \
        user_files "$group" replace "$destination" "$owner" "$group" "$permissions" "$expected" || return 1
    # Root verifies content and metadata through the same O_NOFOLLOW descriptor.
    file_ops verify "$destination" "$expected" "$owner" "$group" "$permissions"
}

service_property() { userctl show "$UNIT" --property="$1" --value; }

restart_safe() {
    local pid status state
    pid=$(service_property MainPID) || return 1
    [[ $pid =~ ^[0-9]+$ ]] || return 1
    # A failed restart may leave no main process.
    if [[ $pid == 0 ]]; then
        state=$(service_property ActiveState) || return 1
        [[ $state == inactive || $state == failed ]]
        return
    fi
    if pgrep -P "$pid" >/dev/null; then
        if [[ $force != 1 ]]; then
            printf 'Unit has child processes; refusing restart (use --force to override)\n' >&2
            return 1
        fi
        printf '%s\n' '--force: restarting unit with child processes' >&2
    else
        status=$?
        [[ $status == 1 ]] || return 1
    fi
}

restart_unit() {
    userctl daemon-reload || return 1
    [[ $(service_property KillMode) == control-group ]] || return 1
    if [[ ${1:-} == rollback ]]; then
        # Rollbacks must terminate workers and their children before restarting.
        userctl stop "$UNIT" >/dev/null 2>&1 || return 1
        userctl start "$UNIT" >/dev/null 2>&1 || return 1
    else
        restart_safe || return 1
        userctl restart "$UNIT" >/dev/null 2>&1 || return 1
    fi
    restart_restarts=$(service_property NRestarts) || return 1
    [[ $restart_restarts =~ ^[0-9]+$ ]]
}

verify_service() {
    local expected=$1 previous=$2 invocation pid restarts state stable=$SECONDS deadline=$((SECONDS + 180))
    restarts=${restart_restarts:-$(service_property NRestarts)}
    [[ $restarts =~ ^[0-9]+$ ]] || return 1
    invocation=$(service_property InvocationID) || return 1
    pid=$(service_property MainPID) || return 1
    [[ -n $invocation && $invocation != "$previous" && $pid =~ ^[1-9][0-9]*$ ]] || return 1
    while (( SECONDS < deadline )); do
        [[ $(service_property InvocationID) == "$invocation" &&
           $(service_property MainPID) == "$pid" &&
           $(service_property NRestarts) == "$restarts" &&
           $(sha "$LIVE") == "$expected" ]] || return 1
        state=$(service_property ActiveState) || return 1
        if [[ $state == active ]]; then
            if (( SECONDS - stable >= 5 )); then
                [[ $(service_property ActiveState) == active &&
                   $(service_property InvocationID) == "$invocation" &&
                   $(service_property MainPID) == "$pid" &&
                   $(service_property NRestarts) == "$restarts" ]] && return 0
                return 1
            fi
        elif [[ $state == activating ]]; then
            stable=$SECONDS
        else
            return 1
        fi
        sleep 1
    done
    return 1
}

cleanup() {
    local status=$? failed=0 previous
    trap - EXIT HUP INT TERM
    set +e
    if [[ $transaction == 1 && $committed == 0 ]]; then
        printf 'Restoring files after failed operation\n' >&2
        atomic_file "$rollback/live" "$LIVE" "$live_uid" "$live_gid" "$live_mode" "$live_sha" || failed=1
        previous=$(service_property InvocationID) || failed=1
        restart_unit rollback && [[ $(sha "$LIVE") == "$live_sha" ]] &&
            verify_service "$live_sha" "$previous" || failed=1
        if [[ $mode == install && $failed == 0 ]]; then
            rm -f -- "$BACKUPS/current" || failed=1
        fi
    fi
    if [[ $status == 6 ]]; then failed=1; fi
    if [[ $failed == 0 && -n $rollback ]]; then rm -rf -- "$rollback"; fi
    if [[ -n $private ]]; then rm -rf -- "$private"; fi
    if [[ $failed != 0 ]]; then
        printf 'Rollback incomplete; owner reconciliation required; backup retained\n' >&2
        status=6
    fi
    exit "$status"
}
