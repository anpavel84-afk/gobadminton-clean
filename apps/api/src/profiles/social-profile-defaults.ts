import type { Pool, PoolClient } from "pg";

/** Safe public display fallback — never use email or invent a city. */
export const SOCIAL_PROFILE_SAFE_DISPLAY_NAME = "Игрок";

export const DIRECTORY_VISIBILITY_PROVENANCE = {
  OWNER_DEFAULT: "owner_default",
  USER_CONSENT: "user_consent",
  USER_OPT_OUT: "user_opt_out",
  /** Pre-#448 row whose OFF/ON was not an Owner product default and lacks opt-out proof. */
  LEGACY: "legacy",
} as const;

export type DirectoryVisibilityProvenance =
  (typeof DIRECTORY_VISIBILITY_PROVENANCE)[keyof typeof DIRECTORY_VISIBILITY_PROVENANCE];

export type EnsureDefaultSocialProfileInput = {
  userId: string;
  /**
   * Ignored for new automatic public names (MOD-V2-A): always trusted Игрок.
   * Kept on the type for call-site compatibility; account/provider names stay private.
   */
  displayName?: string | null;
  /** Only an actual optional city — never invent one. */
  cityId?: string | null;
};

/**
 * True when a public display candidate looks like a mailbox address.
 * Private account/provider names may equal a mailbox; those must not become public names.
 */
export function isEmailShapedDisplayName(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > 320) return false;
  const at = trimmed.indexOf("@");
  if (at <= 0 || at !== trimmed.lastIndexOf("@")) return false;
  const local = trimmed.slice(0, at);
  const domain = trimmed.slice(at + 1);
  if (!local || !domain || domain.startsWith(".") || domain.endsWith(".")) {
    return false;
  }
  return domain.includes(".");
}

/**
 * Trusted constant for NEW automatic public name copies (defaults, avatar missing-profile,
 * Radar bootstrap/empty-name, unified missing-profile). Never copies account/provider names.
 * Explicit moderated rename remains the path for personalization.
 */
export function safeAutogeneratedPublicDisplayName(
  _raw?: string | null | undefined,
): string {
  return SOCIAL_PROFILE_SAFE_DISPLAY_NAME;
}

/**
 * Public DTO / directory / radar / friendship peer boundary (#450 / MOD-V2-A).
 * Scrubs email-shaped or empty stored social-profile names; does not rewrite storage.
 * Separated from automatic-name helper so existing legitimate social names remain visible.
 */
export function safePublicDisplayName(raw: string | null | undefined): string {
  const trimmed = (raw ?? "").trim();
  if (!trimmed || isEmailShapedDisplayName(trimmed)) {
    return SOCIAL_PROFILE_SAFE_DISPLAY_NAME;
  }
  return trimmed.slice(0, 80);
}

/**
 * Materialize a missing social profile with Owner #448 defaults
 * (directory ON + contact requests, owner_default provenance, no consent stamps).
 *
 * Atomic guard matches migration 0049 missing-ACTIVE insert: only users with
 * status='active' and no effective account.access / profile.public /
 * social.directory restriction (revoked_at / starts_at / expires_at vs
 * clock_timestamp()). INSERT … SELECT … ON CONFLICT DO NOTHING — never updates
 * an existing row (preserves explicit OFF); never materializes for inactive or
 * restricted accounts. All callers share this helper.
 */
export async function ensureDefaultSocialProfile(
  client: Pool | PoolClient,
  input: EnsureDefaultSocialProfileInput,
): Promise<void> {
  const displayName = safeAutogeneratedPublicDisplayName(input.displayName);
  const cityId = input.cityId ?? null;
  await client.query(
    `INSERT INTO player_social_profiles (
       user_id,
       display_name,
       city_id,
       directory_visible,
       contact_policy,
       directory_visibility_provenance,
       social_eligible,
       version
     )
     SELECT
       u.id,
       $2,
       $3,
       true,
       'requests',
       $4,
       true,
       1
     FROM users u
     WHERE u.id = $1
       AND u.status = 'active'
       AND NOT EXISTS (
         SELECT 1 FROM user_restrictions ur
         WHERE ur.user_id = u.id
           AND ur.capability IN ('account.access', 'profile.public', 'social.directory')
           AND ur.revoked_at IS NULL
           AND ur.starts_at <= clock_timestamp()
           AND ur.expires_at > clock_timestamp()
       )
     ON CONFLICT (user_id) DO NOTHING`,
    [
      input.userId,
      displayName,
      cityId,
      DIRECTORY_VISIBILITY_PROVENANCE.OWNER_DEFAULT,
    ],
  );
}
