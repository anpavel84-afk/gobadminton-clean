import { describe, expect, it, vi } from "vitest";
import {
  DIRECTORY_VISIBILITY_PROVENANCE,
  SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
  ensureDefaultSocialProfile,
  isEmailShapedDisplayName,
  safeAutogeneratedPublicDisplayName,
  safePublicDisplayName,
} from "../../src/profiles/social-profile-defaults";

describe("safeAutogeneratedPublicDisplayName (MOD-V2-A trusted Игрок)", () => {
  it("always uses Игрок for automatic new public names", () => {
    expect(isEmailShapedDisplayName("player@mail.example")).toBe(true);
    expect(safeAutogeneratedPublicDisplayName("player@mail.example")).toBe(
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
    );
    expect(safeAutogeneratedPublicDisplayName("  Анна Смирнова  ")).toBe(
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
    );
    expect(safeAutogeneratedPublicDisplayName(null)).toBe(
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
    );
  });
});

describe("safePublicDisplayName (#450 public DTO boundary)", () => {
  it("scrubs legacy stored email-shaped and empty values without inventing a city", () => {
    expect(safePublicDisplayName("legacy.user@provider.example")).toBe(
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
    );
    expect(safePublicDisplayName("   ")).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
    expect(safePublicDisplayName(null)).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
  });

  it("keeps ordinary public names and stays separate from the automatic helper", () => {
    expect(safePublicDisplayName("Кирилл Панов")).toBe("Кирилл Панов");
    expect(safePublicDisplayName).not.toBe(safeAutogeneratedPublicDisplayName);
  });
});

describe("ensureDefaultSocialProfile (#448 / MOD-V2-A)", () => {
  it("inserts via guarded SELECT for active unrestricted users only", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 1, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, { userId: "user-1" });
    expect(query).toHaveBeenCalledTimes(1);
    const [sql, params] = query.mock.calls[0]!;
    const text = String(sql);
    expect(text).toMatch(/INSERT INTO player_social_profiles/i);
    expect(text).toMatch(/SELECT[\s\S]*FROM users u/i);
    expect(text).toMatch(/u\.status\s*=\s*'active'/i);
    expect(text).toMatch(/account\.access/);
    expect(text).toMatch(/profile\.public/);
    expect(text).toMatch(/social\.directory/);
    expect(text).toMatch(/revoked_at IS NULL/i);
    expect(text).toMatch(/starts_at\s*<=\s*clock_timestamp\(\)/i);
    expect(text).toMatch(/expires_at\s*>\s*clock_timestamp\(\)/i);
    expect(text).toMatch(/ON CONFLICT \(user_id\) DO NOTHING/i);
    expect(text).not.toMatch(/VALUES\s*\(/i);
    expect(text).not.toMatch(/UPDATE/i);
    expect(params).toEqual([
      "user-1",
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
      null,
      DIRECTORY_VISIBILITY_PROVENANCE.OWNER_DEFAULT,
    ]);
  });

  it("never copies provider/account names into new automatic public defaults", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 0, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-2",
      displayName: "  Provider Name  ",
      cityId: "city-uuid",
    });
    const [, params] = query.mock.calls[0]!;
    expect(params).toEqual([
      "user-2",
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
      "city-uuid",
      DIRECTORY_VISIBILITY_PROVENANCE.OWNER_DEFAULT,
    ]);
  });

  it("never publishes an email-shaped automatic name", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 1, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-email-shaped",
      displayName: "legacy.user@provider.example",
    });
    expect(query.mock.calls[0]![1][1]).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
  });

  it("ignores oversized automatic candidates and uses Игрок", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 1, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-3",
      displayName: "x".repeat(100),
    });
    expect(query.mock.calls[0]![1][1]).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
    query.mockClear();
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-4",
      displayName: "   ",
    });
    expect(query.mock.calls[0]![1][1]).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
  });
});
