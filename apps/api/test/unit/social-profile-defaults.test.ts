import { describe, expect, it, vi } from "vitest";
import {
  DIRECTORY_VISIBILITY_PROVENANCE,
  SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
  ensureDefaultSocialProfile,
  isEmailShapedDisplayName,
  safeAutogeneratedPublicDisplayName,
} from "../../src/profiles/social-profile-defaults";

describe("safeAutogeneratedPublicDisplayName (#448)", () => {
  it("falls back to Игрок for email-shaped automatic names", () => {
    expect(isEmailShapedDisplayName("player@mail.example")).toBe(true);
    expect(safeAutogeneratedPublicDisplayName("player@mail.example")).toBe(
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
    );
  });

  it("keeps a normal non-email public name", () => {
    expect(isEmailShapedDisplayName("Анна Смирнова")).toBe(false);
    expect(safeAutogeneratedPublicDisplayName("  Анна Смирнова  ")).toBe(
      "Анна Смирнова",
    );
  });
});

describe("ensureDefaultSocialProfile (#448)", () => {
  it("inserts owner_default ON + requests with safe name and no consent/city invention", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 1, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, { userId: "user-1" });
    expect(query).toHaveBeenCalledTimes(1);
    const [sql, params] = query.mock.calls[0]!;
    expect(String(sql)).toMatch(/ON CONFLICT \(user_id\) DO NOTHING/i);
    expect(String(sql)).not.toMatch(/UPDATE/i);
    expect(params).toEqual([
      "user-1",
      SOCIAL_PROFILE_SAFE_DISPLAY_NAME,
      null,
      DIRECTORY_VISIBILITY_PROVENANCE.OWNER_DEFAULT,
    ]);
  });

  it("uses provided normal display name and optional city without inventing consent", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 0, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-2",
      displayName: "  Provider Name  ",
      cityId: "city-uuid",
    });
    const [, params] = query.mock.calls[0]!;
    expect(params).toEqual([
      "user-2",
      "Provider Name",
      "city-uuid",
      DIRECTORY_VISIBILITY_PROVENANCE.OWNER_DEFAULT,
    ]);
  });

  it("never publishes an email-shaped automatic name", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 1, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-email-shaped",
      displayName: "legacy.user@provider.example",
    });
    expect(query.mock.calls[0]![1][1]).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
  });

  it("truncates oversized names and rejects empty provided name via fallback", async () => {
    const query = vi.fn().mockResolvedValue({ rowCount: 1, rows: [] });
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-3",
      displayName: "x".repeat(100),
    });
    expect(query.mock.calls[0]![1][1]).toHaveLength(80);
    query.mockClear();
    await ensureDefaultSocialProfile({ query } as never, {
      userId: "user-4",
      displayName: "   ",
    });
    expect(query.mock.calls[0]![1][1]).toBe(SOCIAL_PROFILE_SAFE_DISPLAY_NAME);
  });
});
